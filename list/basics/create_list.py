# creating a list

## using square brackets

# list of integers
a = [1, 2, 3, 4, 5]

# list of strings
b = ['apple', 'banana', 'cherry']

# mixed data types
c = [1, 'hello', 3.15, True]

print(a)
print(b)
print(c)

# --------------------------------------

## using list() constructor

# from a tuple
d = list((1,2,3))
print(d)

# ------------------------------------------

## creating list with repeated elements

a = [2] * 5

b = [0] * 7

print(a)
print(b)